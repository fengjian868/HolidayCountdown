        public static bool IsPrefectureLevelCity(string name)
        {
            if (string.IsNullOrWhiteSpace(name))
                return false;

            var normalized = name.EndsWith("市") ? name.Substring(0, name.Length - 1) : name;
            return PrefectureLevelCitySet.Contains(normalized);
        }
