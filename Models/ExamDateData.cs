    public static DateTime GetExamDate(int year, int examType, string city)
    {
        var key = city.Trim();
        var dict = examType == 1 ? ZhongKaoDates : GaoKaoDates;

        // 先精确匹配城市
        if (dict.TryGetValue(key, out var date)) return new DateTime(year, date.Month, date.Day);

        // 再按省级行政区匹配（数据中包含省/直辖市/自治区通用日期）
        foreach (var kv in dict)
        {
            if (key.Contains(kv.Key) || kv.Key.Contains(key))
                return new DateTime(year, kv.Value.Month, kv.Value.Day);
        }

        // 默认
        return examType == 1
            ? new DateTime(year, 6, 20)
            : new DateTime(year, 6, 7);
    }

